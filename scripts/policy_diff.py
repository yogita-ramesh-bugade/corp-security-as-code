#!/usr/bin/env python3
"""Summarise what a change to fleet/default.yml does, in plain English (Markdown).

Compares the working copy with a base git ref (default: origin/main):
  python3 scripts/policy_diff.py [base-ref] > diff.md
"""
import subprocess
import sys

import yaml

BASE = sys.argv[1] if len(sys.argv) > 1 else "origin/main"
FILE = "fleet/default.yml"


def load(text):
    return yaml.safe_load(text) or {}


def from_git(ref):
    try:
        return load(subprocess.run(["git", "show", f"{ref}:{FILE}"], check=True,
                                   capture_output=True, text=True).stdout)
    except subprocess.CalledProcessError:
        return {}


def scope(item):
    labels = item.get("labels_include_any") or item.get("labels_include_all")
    return f"ring/labels: {', '.join(labels)}" if labels else "all hosts"


def index(cfg):
    controls = cfg.get("controls") or {}
    apple = controls.get("apple_settings") or controls.get("macos_settings") or {}
    profiles = apple.get("configuration_profiles") or apple.get("custom_settings") or []
    return {
        "Configuration profile": {p["path"]: p for p in profiles if isinstance(p, dict)},
        "Script": {s["path"]: s for s in (controls.get("scripts") or []) if isinstance(s, dict)},
        "Policy": {p["name"]: p for p in (cfg.get("policies") or []) if isinstance(p, dict)},
        "Label": {l["name"]: l for l in (cfg.get("labels") or []) if isinstance(l, dict)},
    }


old, new = index(from_git(BASE)), index(load(open(FILE).read()))
lines = []
for kind in new:
    before, after = old.get(kind, {}), new[kind]
    for key in sorted(after.keys() - before.keys()):
        lines.append(f"- **Adds** {kind.lower()} `{key}` ({scope(after[key])})")
    for key in sorted(before.keys() - after.keys()):
        lines.append(f"- **Removes** {kind.lower()} `{key}`")
    for key in sorted(after.keys() & before.keys()):
        if after[key] != before[key]:
            if scope(after[key]) != scope(before[key]):
                lines.append(f"- **Moves** {kind.lower()} `{key}`: {scope(before[key])} → {scope(after[key])}")
            else:
                lines.append(f"- **Changes** {kind.lower()} `{key}` ({scope(after[key])})")

print("### Fleet change summary\n")
print("\n".join(lines) if lines else "_No changes to profiles, scripts, policies or labels._")
print("\n_Generated by scripts/policy_diff.py. Review the scope before merging._")
